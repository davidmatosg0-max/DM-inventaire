export function esRolSistema(rol?: string): rol is RolUsuario {
  return Boolean(rol && rol in SYSTEM_ROLES);
}

export function obtenerLegacyPermissionsDelRol(rol?: string): string[] {
  return esRolSistema(rol) ? SYSTEM_ROLES[rol].legacyPermissions : [];
}

export function obtenerCanonicalPermissionsDelRol(rol?: string): string[] {
  return esRolSistema(rol) ? SYSTEM_ROLES[rol].canonicalPermissions : [];
}